"""
Gemini AI Forensic Analyzer
Analyzes Windows forensic evidence generated by collect.py and main.py using the Google Gemini API.
"""

from __future__ import annotations

import csv
import json
import os
import sys
from pathlib import Path
from typing import Dict, List, Optional, Tuple

import requests

DEFAULT_MODEL = "gemini-2.5-flash"
API_BASE_URL = "https://generativelanguage.googleapis.com/v1beta/models"


def get_api_key(cli_key: Optional[str] = None) -> Optional[str]:
    """Retrieve Gemini API key from CLI argument or environment variables."""
    return cli_key or os.environ.get("GEMINI_API_KEY") or os.environ.get("GOOGLE_API_KEY")


def read_csv_safely(file_path: Path, max_rows: int = 200) -> List[Dict[str, str]]:
    """Read a CSV file and return rows as list of dicts up to max_rows."""
    if not file_path.is_file() or file_path.stat().st_size == 0:
        return []
    rows = []
    try:
        with open(file_path, "r", encoding="utf-8", errors="replace") as f:
            reader = csv.DictReader(f)
            for i, row in enumerate(reader):
                if i >= max_rows:
                    break
                # Filter out None keys or clean empty spaces
                clean_row = {str(k).strip(): str(v).strip() for k, v in row.items() if k}
                rows.append(clean_row)
    except Exception as e:
        rows.append({"error": f"Failed to read {file_path.name}: {e}"})
    return rows


def summarize_forensic_folder(folder: Path) -> Dict[str, any]:
    """Parse and summarize forensic artifacts from the output directory."""
    summary: Dict[str, any] = {
        "folder": str(folder),
        "host": "Unknown",
        "collection_time": "Unknown",
        "artifacts_present": [],
    }

    # Manifest overview
    manifest_path = folder / "manifest.csv"
    if manifest_path.is_file():
        manifest_rows = read_csv_safely(manifest_path, max_rows=50)
        summary["manifest"] = manifest_rows
        summary["artifacts_present"] = [r.get("name", "") for r in manifest_rows if r.get("name")]

    # OS Info
    os_info = read_csv_safely(folder / "os_info.csv", max_rows=5)
    if os_info:
        summary["os_info"] = os_info[0]
        summary["host"] = os_info[0].get("CSName", "Unknown")

    # Timezone
    tz = read_csv_safely(folder / "timezone.csv", max_rows=2)
    if tz:
        summary["timezone"] = tz[0]

    # Running Processes - Highlight unusual paths or parent-child relations
    procs = read_csv_safely(folder / "processes.csv", max_rows=300)
    suspicious_procs = []
    suspicious_paths = ("appdata", "temp", "tmp", "users\\public", "downloads", "perflogs")
    for p in procs:
        exe = (p.get("ExecutablePath") or "").lower()
        cmd = (p.get("CommandLine") or "").lower()
        if any(sp in exe or sp in cmd for sp in suspicious_paths):
            suspicious_procs.append(p)
    summary["processes_total_sampled"] = len(procs)
    summary["processes_suspicious_location"] = suspicious_procs
    summary["processes_sample"] = procs[:50]  # First 50 processes

    # Network Connections
    tcps = read_csv_safely(folder / "tcp_connections.csv", max_rows=300)
    established_remote = []
    for t in tcps:
        state = t.get("State", "")
        rem_ip = t.get("RemoteAddress", "")
        if state == "Established" and not rem_ip.startswith(("127.", "0.0.", "::", "10.", "192.168.")):
            established_remote.append(t)
    summary["tcp_established_external"] = established_remote
    summary["tcp_sample"] = tcps[:40]

    # DNS Cache
    dns = read_csv_safely(folder / "dns_cache.csv", max_rows=150)
    summary["dns_cache_sample"] = dns[:50]

    # Services
    services = read_csv_safely(folder / "services.csv", max_rows=300)
    non_system_services = []
    for s in services:
        pathname = (s.get("PathName") or "").lower()
        if pathname and "system32" not in pathname and "windows" not in pathname:
            non_system_services.append(s)
    summary["services_non_system32"] = non_system_services[:40]

    # Scheduled Tasks
    tasks = read_csv_safely(folder / "scheduled_tasks.csv", max_rows=300)
    non_ms_tasks = [t for t in tasks if not (t.get("TaskPath") or "").startswith("\\Microsoft\\Windows")]
    summary["scheduled_tasks_non_ms"] = non_ms_tasks[:40]

    # Users & Admins
    summary["local_admins"] = read_csv_safely(folder / "local_admins.csv", max_rows=20)
    summary["local_users"] = read_csv_safely(folder / "local_users.csv", max_rows=20)

    # Logons
    logons = read_csv_safely(folder / "logons.csv", max_rows=50)
    summary["logons_sample"] = logons[:20]

    return summary


def build_analysis_prompt(forensic_data: Dict[str, any]) -> str:
    """Build a comprehensive DFIR analysis prompt for Gemini."""
    prompt = f"""
You are a Lead Digital Forensics & Incident Response (DFIR) Security Analyst.
Below is structured forensic data collected from a Windows host endpoint.

### TARGET SYSTEM METRICS:
- Hostname: {forensic_data.get('host')}
- Operating System: {json.dumps(forensic_data.get('os_info', {}))}
- Timezone: {json.dumps(forensic_data.get('timezone', {}))}
- Total Collected Artifacts: {len(forensic_data.get('artifacts_present', []))}

### COLLECTED FORENSIC SUMMARY:

1. SUSPICIOUS OR NON-STANDARD PATH PROCESSES:
{json.dumps(forensic_data.get('processes_suspicious_location', []), indent=2)}

2. SAMPLE OF RUNNING PROCESSES (First 50):
{json.dumps(forensic_data.get('processes_sample', []), indent=2)}

3. ESTABLISHED EXTERNAL TCP NETWORK CONNECTIONS:
{json.dumps(forensic_data.get('tcp_established_external', []), indent=2)}

4. SAMPLE OF ACTIVE TCP CONNECTIONS:
{json.dumps(forensic_data.get('tcp_sample', []), indent=2)}

5. RESOLVED DNS CACHE ENTRIES:
{json.dumps(forensic_data.get('dns_cache_sample', []), indent=2)}

6. NON-STANDARD SERVICES (Outside system32/windows):
{json.dumps(forensic_data.get('services_non_system32', []), indent=2)}

7. NON-MICROSOFT SCHEDULED TASKS:
{json.dumps(forensic_data.get('scheduled_tasks_non_ms', []), indent=2)}

8. LOCAL ADMINISTRATORS & USER ACCOUNTS:
Admins: {json.dumps(forensic_data.get('local_admins', []), indent=2)}
Users: {json.dumps(forensic_data.get('local_users', []), indent=2)}

---

### INSTRUCTIONS FOR YOUR ANALYSIS:
Provide a rigorous, professional cybersecurity triage and investigation report in GitHub Flavored Markdown:

1. **Executive Summary**:
   - Host assessment overview.
   - **Overall Risk Rating**: [LOW | MEDIUM | HIGH | CRITICAL] with clear justification.
2. **Process Execution Analysis**:
   - Evaluate process hierarchy, suspicious execution locations (AppData, Temp, Users), masquerading (e.g., svchost.exe outside System32), or LOLBins.
3. **Network & Communications Analysis**:
   - Highlight any suspicious outbound sockets, rare ports, unmapped foreign addresses, or suspicious DNS queries.
4. **Persistence & Privilege Escalation Analysis**:
   - Scrutinize non-standard scheduled tasks, third-party services, and local administrator membership.
5. **MITRE ATT&CK Framework Mapping**:
   - Table of mapped Tactics, Techniques, and IDs (e.g. T1059, T1053, T1543, T1071).
6. **Recommended Immediate Containment & Remediation Actions**:
   - Step-by-step guidance for the incident response team.
"""
    return prompt.strip()


def query_gemini_api(prompt: str, api_key: str, model: str = DEFAULT_MODEL) -> Tuple[bool, str]:
    """
    Call Gemini API using the official REST API (works with standard requests library).
    Falls back gracefully without external complex SDK dependencies.
    """
    url = f"{API_BASE_URL}/{model}:generateContent?key={api_key}"
    headers = {"Content-Type": "application/json"}
    payload = {
        "contents": [
            {
                "parts": [
                    {"text": prompt}
                ]
            }
        ],
        "generationConfig": {
            "temperature": 0.2,
            "maxOutputTokens": 8192,
        }
    }

    try:
        response = requests.post(url, headers=headers, json=payload, timeout=120)
    except requests.RequestException as e:
        return False, f"Network error contacting Gemini API: {e}"

    if response.status_code != 200:
        return False, f"Gemini API error (HTTP {response.status_code}): {response.text}"

    data = response.json()
    try:
        candidates = data.get("candidates", [])
        if not candidates:
            return False, "Gemini returned no candidates."
        parts = candidates[0].get("content", {}).get("parts", [])
        if not parts:
            return False, "Gemini returned empty parts."
        text = parts[0].get("text", "")
        return True, text
    except Exception as e:
        return False, f"Failed to parse Gemini response: {e}\nRaw: {data}"


def analyze_evidence_folder(
    folder: Path | str,
    api_key: Optional[str] = None,
    model: str = DEFAULT_MODEL,
    save_report: bool = True,
) -> Tuple[bool, str, Optional[Path]]:
    """
    Complete analysis pipeline:
    1. Summarizes forensic CSVs in folder
    2. Builds analysis prompt
    3. Queries Gemini API
    4. Writes ai_analysis_report.md in folder
    """
    folder_path = Path(folder).resolve()
    if not folder_path.is_dir():
        return False, f"Evidence folder not found: {folder_path}", None

    key = get_api_key(api_key)
    if not key:
        return (
            False,
            "Error: Gemini API Key not found. Please provide --gemini-key or set GEMINI_API_KEY environment variable.\n"
            "You can get a free API key at: https://aistudio.google.com/",
            None,
        )

    print(f"[*] Parsing forensic artifacts from {folder_path} ...")
    forensic_data = summarize_forensic_folder(folder_path)

    print(f"[*] Building forensic prompt (Target Host: {forensic_data.get('host')}) ...")
    prompt = build_analysis_prompt(forensic_data)

    print(f"[*] Sending data to Gemini API ({model}) for threat analysis ...")
    success, report_text = query_gemini_api(prompt, key, model)

    if not success:
        return False, report_text, None

    report_path = None
    if save_report:
        report_path = folder_path / "ai_analysis_report.md"
        with open(report_path, "w", encoding="utf-8") as f:
            f.write(f"# Forensic AI Threat Analysis Report\n\n")
            f.write(f"- **Target Host**: `{forensic_data.get('host')}`\n")
            f.write(f"- **Analyzed Directory**: `{folder_path}`\n")
            f.write(f"- **Analysis Model**: `{model}`\n")
            f.write(f"- **Generated At**: `{forensic_data.get('collection_time')}`\n\n")
            f.write(f"---\n\n")
            f.write(report_text)
        print(f"[+] AI Analysis Report saved to: {report_path}")

    return True, report_text, report_path


if __name__ == "__main__":
    import argparse

    parser = argparse.ArgumentParser(description="Analyze forensic evidence folder using Gemini API.")
    parser.add_argument("--folder", required=True, help="Path to evidence folder containing CSVs")
    parser.add_argument("--key", help="Gemini API Key (or set GEMINI_API_KEY env var)")
    parser.add_argument("--model", default=DEFAULT_MODEL, help=f"Gemini model (default: {DEFAULT_MODEL})")
    args = parser.parse_args()

    ok, result, out_file = analyze_evidence_folder(args.folder, args.key, args.model)
    if ok:
        print("\n" + "=" * 80)
        print("GEMINI FORENSIC THREAT REPORT:")
        print("=" * 80 + "\n")
        print(result)
    else:
        print(f"\n[!] Analysis failed: {result}")
        sys.exit(1)
